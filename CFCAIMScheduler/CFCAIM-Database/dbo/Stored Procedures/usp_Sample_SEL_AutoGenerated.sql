CREATE PROCEDURE [dbo].[usp_Sample_SEL_AutoGenerated]
	  @DataSourceTypeid  INT		
	


AS
BEGIN
SET NOCOUNT ON;
DECLARE @RecordID INT = 0
DECLARE @ErrorNumber INT = 0
DECLARE @ErrorMessage VARCHAR(200) = ''


SET @RecordID = (SELECT isnull(max(SampleID) ,1) as LastSample 

				FROM
					dbo.Sample S with (nolock)

				INNER JOIN 
					dbo.DataSourceType DST with (nolock)
						ON S.DataSourceTypeID = DST.DataSourceTypeID

				WHERE S.DataSourceTypeID = @DataSourceTypeid )


SELECT 
	  @RecordID as RecordID
	, @ErrorNumber AS ErrorNumber
	, @ErrorMessage AS ErrorMessage

END